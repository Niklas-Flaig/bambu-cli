import { describe, expect, test } from "bun:test";
import { zipSync, strToU8 } from "fflate";
import { inspectArchive, InspectError } from "../src/commands/inspect.ts";

const SLICE_INFO = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header>
    <header_item key="X-BBL-Client-Type" value="slicer"/>
  </header>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="printer_model_id" value="C12"/>
    <metadata key="prediction" value="4230"/>
    <metadata key="weight" value="12.34"/>
    <filament id="1" type="PLA" used_m="4.12" used_g="12.34" color="#FF6A13"/>
  </plate>
</config>`;

function build3mf(withThumbnail = true): Uint8Array {
  const entries: Record<string, Uint8Array> = {
    "3D/3dmodel.model": strToU8("<model/>"),
    "Metadata/plate_1.gcode": strToU8("; generated by test\nG28\n"),
    "Metadata/slice_info.config": strToU8(SLICE_INFO),
    "[Content_Types].xml": strToU8("<Types/>"),
  };
  if (withThumbnail) entries["Metadata/plate_1.png"] = new Uint8Array([0x89, 0x50, 0x4e, 0x47]);
  return zipSync(entries);
}

describe("inspectArchive", () => {
  test("reads plates, time, filament and printer model", () => {
    const result = inspectArchive("benchy.gcode.3mf", build3mf());
    expect(result.plates).toHaveLength(1);
    expect(result.printerModelId).toBe("C12");
    const plate = result.plates[0]!;
    expect(plate.index).toBe(1);
    expect(plate.printSeconds).toBe(4230);
    expect(plate.hasThumbnail).toBe(true);
    expect(plate.filaments[0]?.type).toBe("PLA");
    expect(plate.filaments[0]?.usedG).toBeCloseTo(12.34);
  });

  test("flags a missing thumbnail", () => {
    const result = inspectArchive("x.gcode.3mf", build3mf(false));
    expect(result.plates[0]!.hasThumbnail).toBe(false);
  });

  test("rejects an archive without plate gcode", () => {
    const empty = zipSync({ "foo.txt": strToU8("hi") });
    expect(() => inspectArchive("x.3mf", empty)).toThrow(InspectError);
  });

  test("rejects non-zip bytes", () => {
    expect(() => inspectArchive("x.3mf", new Uint8Array([1, 2, 3]))).toThrow(InspectError);
  });
});
